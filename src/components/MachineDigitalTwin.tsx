import React, { Suspense, lazy, useState } from 'react';
import { motion, AnimatePresence } from 'motion/react';
import { Activity, Flame, Gauge, Zap, ShieldAlert, Cpu, Layers } from 'lucide-react';
import { TelemetryState, PredictionResult, FailureMode } from '../types';
import { computeRulForecast } from '../utils/mlEngine';

// Lazy-loaded so the three.js chunk only downloads when the user opens 3D.
const ThreeDTwin = lazy(() => import('./ThreeDTwin').then((m) => ({ default: m.ThreeDTwin })));

interface MachineDigitalTwinProps {
  telemetry: TelemetryState;
  prediction: PredictionResult;
  isStreaming?: boolean;
}

interface ComponentHotspot {
  id: string;
  name: string;
  failureMode: FailureMode;
  x: number; // percentage
  y: number;
  icon: React.ElementType;
  description: string;
  metricLabel: string;
  getMetricValue: (t: TelemetryState, p: PredictionResult) => string;
}

export const MachineDigitalTwin: React.FC<MachineDigitalTwinProps> = ({
  telemetry,
  prediction,
  isStreaming = false
}) => {
  const [activeHotspot, setActiveHotspot] = useState<string | null>('tool');
  const [viewMode, setViewMode] = useState<'cad' | 'thermal' | 'stress'>('cad');
  const [show3d, setShow3d] = useState(false);

  const hotspots: ComponentHotspot[] = [
    {
      id: 'tool',
      name: 'Carbide Cutting Insert (Flank Face)',
      failureMode: 'TWF',
      x: 82,
      y: 50,
      icon: Gauge,
      description: 'Primary rock drilling carbide cutter subject to abrasive wear & micro-fracture.',
      metricLabel: 'Tool Wear Accumulation',
      getMetricValue: (t) => `${t.toolWear} min (Limit: 200 min)`
    },
    {
      id: 'jacket',
      name: 'Heat Exchanger Coolant Jacket',
      failureMode: 'HDF',
      x: 52,
      y: 30,
      icon: Flame,
      description: 'Liquid cooling channels extracting thermodynamic heat generated by deep bore friction.',
      metricLabel: 'Thermal Dissipation Delta (ΔT)',
      getMetricValue: (_, p) => `${p.tempDiffKelvin.toFixed(1)} K (Min: 8.6 K)`
    },
    {
      id: 'motor',
      name: 'Electromagnetic Stator & Drive Inverter',
      failureMode: 'PWF',
      x: 22,
      y: 50,
      icon: Zap,
      description: 'High-torque synchronous motor providing rotational drive force across 1100-2900 RPM.',
      metricLabel: 'Active Electromechanical Power',
      getMetricValue: (_, p) => `${(p.powerWatts / 1000).toFixed(2)} kW (3.5 - 9.0 kW)`
    },
    {
      id: 'bearing',
      name: 'Torque Transmission & Thrust Bearing Hub',
      failureMode: 'OSF',
      x: 48,
      y: 72,
      icon: Activity,
      description: 'Heavy duty roller bearings absorbing mechanical torque fatigue and axial thrust load.',
      metricLabel: 'Overstrain Stress Product',
      getMetricValue: (_, p) => `${p.overstrainProduct.toFixed(0)} min·Nm`
    }
  ];

  const selectedHotspotData = hotspots.find(h => h.id === activeHotspot);
  const rulForecast = computeRulForecast(telemetry, prediction.machineFailureProbability, prediction.estimatedRULHours);

  // Rotation duration based on RPM (faster RPM = faster spin)
  const spinSpeedSec = Math.max(0.4, 4000 / Math.max(800, telemetry.rotationalSpeed));

  return (
    <div className="relative forge-card p-5 md:p-6 overflow-hidden">
      {/* Header bar */}
      <div className="flex flex-wrap items-center justify-between gap-4 mb-5 pb-4 border-b border-slate-800/60">
        <div className="flex items-center gap-3">
          <div className="w-9 h-9 rounded-lg bg-cyan-500/10 border border-cyan-500/30 flex items-center justify-center text-cyan-400">
            <Cpu className="w-5 h-5" />
          </div>
          <div>
            <div className="flex items-center gap-2">
              <h2 className="forge-title" style={{ fontSize: 22 }}>
                CAD DIGITAL TWIN // ROTARY DRILL SPINDLE
              </h2>
              <span className={`px-2 py-0.5 rounded-full border forge-label ${isStreaming ? 'text-emerald-300 border-emerald-500/40 bg-emerald-950/40' : 'text-slate-400 border-slate-700 bg-slate-950/40'}`}>
                {isStreaming ? '● LIVE' : 'PAUSED'}
              </span>
              <span className={`px-2 py-0.5 text-xs font-mono font-medium rounded-full border ${
                prediction.isMachineFailure
                  ? 'bg-rose-500/10 text-rose-400 border-rose-500/30'
                  : 'bg-emerald-500/10 text-emerald-400 border-emerald-500/30'
              }`}>
                {prediction.isMachineFailure ? 'ANOMALY DETECTED' : 'SYSTEM HEALTHY'}
              </span>
            </div>
            <p className="text-xs text-slate-400">
              Interactive 2.5D cross-section inspection • Synchronized with live telemetry
            </p>
          </div>
        </div>

        {/* View Mode Toggle */}
        <div className="flex items-center bg-slate-950/80 p-1 rounded-xl border border-slate-800">
          <button
            type="button"
            onClick={() => setViewMode('cad')}
            className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium transition-all ${
              viewMode === 'cad'
                ? 'bg-cyan-500/20 text-cyan-300 border border-cyan-500/30 shadow-sm'
                : 'text-slate-400 hover:text-slate-200'
            }`}
          >
            <Layers className="w-3.5 h-3.5" />
            Schematic
          </button>
          <button
            type="button"
            onClick={() => setViewMode('thermal')}
            className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium transition-all ${
              viewMode === 'thermal'
                ? 'bg-amber-500/20 text-amber-300 border border-amber-500/30 shadow-sm'
                : 'text-slate-400 hover:text-slate-200'
            }`}
          >
            <Flame className="w-3.5 h-3.5" />
            Thermal Heatmap
          </button>
          <button
            type="button"
            onClick={() => setViewMode('stress')}
            className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium transition-all ${
              viewMode === 'stress'
                ? 'bg-purple-500/20 text-purple-300 border border-purple-500/30 shadow-sm'
                : 'text-slate-400 hover:text-slate-200'
            }`}
          >
            <Activity className="w-3.5 h-3.5" />
            Stress Strain
          </button>
        </div>
      </div>

      {/* Main Visual Stage */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6 items-center">
        {/* Machinery Vector SVG Stage */}
        <div className="lg:col-span-8 relative aspect-[16/9] min-h-[280px] sm:min-h-[340px] rounded-xl bg-slate-950/90 border border-slate-800/80 flex items-center justify-center p-4 overflow-hidden group">
          {/* Engineering blueprint grid lines */}
          <div
            className="absolute inset-0 opacity-15"
            style={{
              backgroundImage: 'radial-gradient(circle, #9299A5 1px, transparent 1px)',
              backgroundSize: '24px 24px'
            }}
          />

          {/* Crosshair coordinate markers */}
          <div className="absolute top-3 left-3 text-[10px] font-mono text-slate-500 flex items-center gap-2">
            <span className="w-1.5 h-1.5 rounded-full bg-cyan-400 animate-ping" />
            NODE: BORE_ACTUATOR_V3 // LATENCY: 2ms
          </div>

          <div className="absolute bottom-3 right-3 text-[10px] font-mono text-slate-500">
            RPM: {telemetry.rotationalSpeed} | TQ: {telemetry.torque} Nm | ΔT: {prediction.tempDiffKelvin.toFixed(1)} K
          </div>

          {/* RUL countdown overlay in the scene (Feature 3) */}
          <div className={`absolute top-3 right-3 z-20 rounded-lg border px-3 py-2 text-right font-mono backdrop-blur-md ${
            prediction.isMachineFailure
              ? 'bg-rose-950/80 border-rose-500/50 text-rose-200'
              : 'bg-slate-950/80 border-slate-700 text-slate-200'
          }`}>
            <div className="text-[9px] tracking-wider text-slate-400">
              {prediction.isMachineFailure ? 'FAILURE WINDOW — OPERATING HOURS' : 'REMAINING USEFUL LIFE'}
            </div>
            <div className="text-sm font-bold">
              {rulForecast.lowHours}–{rulForecast.highHours} h
            </div>
            <div className="text-[10px] text-slate-400">
              Central ~{rulForecast.centralHours} h • Wear budget {rulForecast.wearBudgetUsedPct.toFixed(0)}% used
            </div>
          </div>

          {/* SVG Industrial Assembly Drawing */}
          <svg
            viewBox="0 0 800 400"
            className="w-full h-full max-h-[320px] select-none filter drop-shadow-[0_0_20px_rgba(216,220,227,0.12)]"
          >
            <defs>
              {/* Thermal Gradient */}
              <linearGradient id="thermalGrad" x1="0%" y1="0%" x2="100%" y2="0%">
                <stop offset="0%" stopColor="#D8DCE3" stopOpacity="0.8" />
                <stop offset="50%" stopColor="#9299A5" stopOpacity="0.8" />
                <stop
                  offset="100%"
                  stopColor={telemetry.processTemp > 310 ? '#ef4444' : '#555C68'}
                  stopOpacity="0.9"
                />
              </linearGradient>

              {/* Stress Strain Gradient */}
              <linearGradient id="stressGrad" x1="0%" y1="0%" x2="100%" y2="0%">
                <stop offset="0%" stopColor="#F5F6F8" />
                <stop offset="60%" stopColor="#9299A5" />
                <stop
                  offset="100%"
                  stopColor={telemetry.torque > 55 ? '#ef4444' : '#555C68'}
                />
              </linearGradient>

              {/* Machinery Metallic Pattern */}
              <linearGradient id="metalGrad" x1="0%" y1="0%" x2="0%" y2="100%">
                <stop offset="0%" stopColor="#2A2E36" />
                <stop offset="50%" stopColor="#191C22" />
                <stop offset="100%" stopColor="#08090C" />
              </linearGradient>

              {/* Spindle Glow */}
              <filter id="glow" x="-20%" y="-20%" width="140%" height="140%">
                <feGaussianBlur stdDeviation="6" result="blur" />
                <feComposite in="SourceGraphic" in2="blur" operator="over" />
              </filter>
            </defs>

            {/* Base Housing Flange */}
            <rect
              x="60"
              y="110"
              width="140"
              height="180"
              rx="12"
              fill={viewMode === 'thermal' ? 'url(#thermalGrad)' : viewMode === 'stress' ? 'url(#stressGrad)' : 'url(#metalGrad)'}
              stroke="#9299A5"
              strokeWidth="2"
              strokeDasharray="6,4"
              opacity="0.8"
            />
            {/* Motor Stator Windings */}
            <g opacity="0.6">
              {[130, 150, 170, 190, 210, 230, 250, 270].map((y, idx) => (
                <line
                  key={idx}
                  x1="70"
                  y1={y}
                  x2="190"
                  y2={y}
                  stroke="#D8DCE3"
                  strokeWidth="1.5"
                  strokeDasharray="3,3"
                />
              ))}
            </g>

            {/* Middle Transmission Casing & Heat Exchanger */}
            <rect
              x="200"
              y="130"
              width="240"
              height="140"
              rx="8"
              fill={viewMode === 'thermal' ? 'url(#thermalGrad)' : viewMode === 'stress' ? 'url(#stressGrad)' : '#191C22'}
              stroke="#9299A5"
              strokeWidth="2.5"
            />

            {/* Coolant fluid helical wave pattern */}
            <path
              d="M 220 160 Q 260 140 300 160 T 380 160 T 420 160"
              fill="none"
              stroke={telemetry.processTemp - telemetry.airTemp < 8.6 ? '#f59e0b' : '#9299A5'}
              strokeWidth="3"
              strokeDasharray="6 4"
              className="animate-pulse"
            />
            <path
              d="M 220 240 Q 260 220 300 240 T 380 240 T 420 240"
              fill="none"
              stroke={telemetry.processTemp - telemetry.airTemp < 8.6 ? '#f59e0b' : '#9299A5'}
              strokeWidth="3"
              strokeDasharray="6 4"
              className="animate-pulse"
            />

            {/* Main Central Drive Shaft (Spindle) */}
            <rect
              x="120"
              y="180"
              width="450"
              height="40"
              rx="4"
              fill="#475569"
              stroke="#94a3b8"
              strokeWidth="1.5"
            />

            {/* Rotating Gear Teeth animation on shaft */}
            <g transform="translate(320, 200)">
              <circle
                r="36"
                fill="none"
                stroke="#D8DCE3"
                strokeWidth="2.5"
                strokeDasharray="8 6"
                style={{
                  transformOrigin: 'center',
                  animation: `spin ${spinSpeedSec}s linear infinite`
                }}
              />
            </g>

            {/* Bearing Hub Assembly */}
            <g transform="translate(430, 200)">
              <circle r="44" fill="#0f172a" stroke="#f59e0b" strokeWidth="2" />
              <circle
                r="30"
                fill="none"
                stroke="#cbd5e1"
                strokeWidth="3"
                strokeDasharray="6 4"
                style={{
                  transformOrigin: 'center',
                  animation: `spin ${spinSpeedSec * 1.5}s linear infinite reverse`
                }}
              />
              {[0, 45, 90, 135, 180, 225, 270, 315].map((angle, i) => (
                <circle
                  key={i}
                  cx={26 * Math.cos((angle * Math.PI) / 180)}
                  cy={26 * Math.sin((angle * Math.PI) / 180)}
                  r="5"
                  fill="#e2e8f0"
                />
              ))}
            </g>

            {/* Rotary Tool Chuck & Cutter Head */}
            <path
              d="M 570 150 L 670 170 L 730 200 L 670 230 L 570 250 Z"
              fill={viewMode === 'thermal' ? '#ef4444' : viewMode === 'stress' ? '#ef4444' : '#2A2E36'}
              stroke="#D8DCE3"
              strokeWidth="2"
            />

            {/* Carbide Drill Flute Grooves with Rotation */}
            <g
              transform="translate(680, 200)"
              style={{
                transformOrigin: 'center',
                animation: `spin ${spinSpeedSec * 0.8}s linear infinite`
              }}
            >
              <line x1="-30" y1="-25" x2="30" y2="25" stroke="#f8fafc" strokeWidth="3" />
              <line x1="-30" y1="25" x2="30" y2="-25" stroke="#f8fafc" strokeWidth="3" />
              <circle r="12" fill={telemetry.toolWear > 200 ? '#ef4444' : '#10b981'} />
            </g>

            {/* Dynamic Failure/Wear Sparks if near threshold */}
            {(telemetry.toolWear > 190 || telemetry.torque > 60) && (
              <g transform="translate(740, 200)">
                <circle r="6" fill="#f59e0b" className="animate-ping" />
                <line x1="0" y1="0" x2="25" y2="-20" stroke="#f59e0b" strokeWidth="2" strokeLinecap="round" />
                <line x1="0" y1="0" x2="30" y2="15" stroke="#ef4444" strokeWidth="2" strokeLinecap="round" />
                <line x1="0" y1="0" x2="20" y2="30" stroke="#f97316" strokeWidth="2" strokeLinecap="round" />
              </g>
            )}
          </svg>

          {/* Interactive Clickable Hotspot Pins */}
          {hotspots.map((hotspot) => {
            const isSelected = activeHotspot === hotspot.id;
            const isTriggered = prediction.failures[hotspot.failureMode]?.isTriggered;
            const Icon = hotspot.icon;

            return (
              <button
                key={hotspot.id}
                type="button"
                onClick={() => setActiveHotspot(hotspot.id)}
                style={{
                  left: `${hotspot.x}%`,
                  top: `${hotspot.y}%`,
                  transform: 'translate(-50%, -50%)',
                }}
                className={`absolute z-20 flex items-center justify-center w-8 h-8 rounded-full border transition-all duration-300 ${
                  isTriggered
                    ? 'bg-rose-500/90 border-white text-white shadow-lg shadow-rose-500/50 animate-bounce'
                    : isSelected
                    ? 'bg-[#F5F6F8] border-[#D8DCE3] text-[#08090C] scale-110 shadow-lg shadow-black/50'
                    : 'bg-slate-900/90 border-cyan-500/60 text-cyan-400 hover:scale-110 hover:border-cyan-300'
                }`}
                title={hotspot.name}
              >
                <Icon className="w-4 h-4" />
                {isSelected && (
                  <span className="absolute -inset-1 rounded-full border border-[#9299A5] animate-ping pointer-events-none" />
                )}
              </button>
            );
          })}
        </div>

        {/* Selected Component Inspection Telemetry Card */}
        <div className="lg:col-span-4">
          <AnimatePresence mode="wait">
            {selectedHotspotData && (
              <motion.div
                key={selectedHotspotData.id}
                initial={{ opacity: 0, y: 10 }}
                animate={{ opacity: 1, y: 0 }}
                exit={{ opacity: 0, y: -10 }}
                className="rounded-xl bg-slate-950/80 border border-slate-800 p-4 space-y-4"
              >
                <div className="flex items-start justify-between gap-2">
                  <div>
                    <span className="forge-label text-[#D8DCE3] bg-[#191C22] px-2 py-0.5 rounded border border-[#2A2E36]">
                      Subsystem Target
                    </span>
                    <h3 className="text-sm font-semibold text-slate-100 mt-1 font-mono">
                      {selectedHotspotData.name}
                    </h3>
                  </div>
                  <div className={`px-2 py-1 rounded text-xs font-mono font-bold ${
                    prediction.failures[selectedHotspotData.failureMode]?.isTriggered
                      ? 'bg-rose-500/20 text-rose-400 border border-rose-500/40'
                      : 'bg-emerald-500/20 text-emerald-400 border border-emerald-500/40'
                  }`}>
                    {selectedHotspotData.failureMode}
                  </div>
                </div>

                <p className="text-xs text-slate-300 leading-relaxed">
                  {selectedHotspotData.description}
                </p>

                <div className="bg-slate-900/90 rounded-lg p-3 border border-slate-800 space-y-2 font-mono">
                  <div className="text-[11px] text-slate-400">
                    {selectedHotspotData.metricLabel}
                  </div>
                  <div className="text-base font-bold text-cyan-300">
                    {selectedHotspotData.getMetricValue(telemetry, prediction)}
                  </div>
                </div>

                <div className="space-y-1.5">
                  <div className="flex justify-between text-xs font-mono">
                    <span className="text-slate-400">Failure Mode Risk:</span>
                    <span className="font-semibold text-slate-200">
                      {(prediction.failures[selectedHotspotData.failureMode]?.probability * 100).toFixed(1)}%
                    </span>
                  </div>
                  <div className="w-full bg-slate-800 rounded-full h-2 overflow-hidden">
                    <motion.div
                      initial={{ width: 0 }}
                      animate={{
                        width: `${prediction.failures[selectedHotspotData.failureMode]?.probability * 100}%`
                      }}
                      className={`h-full rounded-full ${
                        prediction.failures[selectedHotspotData.failureMode]?.isTriggered
                          ? 'bg-rose-500'
                          : prediction.failures[selectedHotspotData.failureMode]?.probability > 0.3
                          ? 'bg-amber-400'
                          : 'bg-cyan-500'
                      }`}
                    />
                  </div>
                  <p className="text-[11px] text-slate-400 italic pt-1">
                    {prediction.failures[selectedHotspotData.failureMode]?.thresholdNote}
                  </p>
                </div>
              </motion.div>
            )}
          </AnimatePresence>

          {/* RUL forecast band (Feature 3) */}
          <div className="mt-4 rounded-xl bg-slate-950/80 border border-slate-800 p-4 space-y-2 font-mono">
            <div className="flex justify-between text-xs">
              <span className="text-slate-400">RUL forecast band</span>
              <span className="font-bold text-amber-300">
                {rulForecast.lowHours}–{rulForecast.highHours} h
              </span>
            </div>
            <div className="flex justify-between text-[11px] text-slate-400">
              <span>Central ~{rulForecast.centralHours} h</span>
              <span>{rulForecast.remainingWearMin} min wear remaining to subsystem critical</span>
            </div>
            <div className="w-full bg-slate-800 rounded-full h-2 overflow-hidden">
              <div
                style={{ width: `${rulForecast.wearBudgetUsedPct}%` }}
                className={`h-full rounded-full ${rulForecast.wearBudgetUsedPct > 85 ? 'bg-rose-500' : rulForecast.wearBudgetUsedPct > 65 ? 'bg-amber-400' : 'bg-cyan-500'}`}
              />
            </div>
            <p className="text-[10px] text-slate-500 leading-relaxed">
              {rulForecast.method}
            </p>
          </div>
        </div>
      </div>

      {/* 3D twin (Part 1 UI, step 3) — on demand, 2D stays the default */}
      <div className="pt-2">
        <button
          type="button"
          onClick={() => setShow3d(!show3d)}
          aria-expanded={show3d}
          className="px-3 py-2 rounded-lg bg-cyan-500/10 hover:bg-cyan-500/20 text-cyan-300 border border-cyan-500/40 text-xs font-mono font-bold"
        >
          {show3d ? 'Hide 3D twin ↑' : 'Open 3D twin (React Three Fiber, loads on demand) →'}
        </button>
        {show3d && (
          <div className="mt-3">
            <Suspense fallback={<p className="text-xs text-slate-400 font-mono">Loading 3D twin…</p>}>
              <ThreeDTwin telemetry={telemetry} prediction={prediction} />
            </Suspense>
          </div>
        )}
      </div>
    </div>
  );
};
